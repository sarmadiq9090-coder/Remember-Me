test('Drive backup contains text and images locally and in the selected sync folder; daily copies are bounded', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'waqt-drive-'));
  const data = path.join(root, 'data'), sync = path.join(root, 'Google Drive');
  fs.mkdirSync(sync); const store = new Store(data);
  const [image] = await importFiles(data, [path.join(__dirname, '../assets/icon.png')]);
  store.change(s => { s.attachments.push(image); saveTask(s, { title: 'صورة وتذكير', body: 'نص مع الصورة', attachments: [image.id] }); });
  let now = Date.now();
  const backup = new DriveBackup(data, () => store.state, () => {}, { clock: () => now });
  await backup.configure(sync);
  await backup.tick();
  const result = backup.status();
  assert.ok(result.lastCopiedAt); assert.equal(result.pending, false);
  assert.ok(fs.existsSync(path.join(result.lastLocalPath, 'data.json')));
  assert.equal(JSON.parse(fs.readFileSync(path.join(result.lastDrivePath, 'data.json'))).tasks[0].body, 'نص مع الصورة');
  assert.deepEqual(fs.readFileSync(path.join(result.lastDrivePath, 'attachments', image.id, image.name)), fs.readFileSync(path.join(__dirname, '../assets/icon.png')));
  assert.equal(JSON.parse(fs.readFileSync(path.join(result.lastDrivePath, 'backup.json'))).kind, 'automatic', 'Checksums travel with the Drive copy');
  await backup.tick(); assert.equal(fs.readdirSync(sync).length, 1);
  const loaded = new DriveBackup(data, () => store.state, () => {}, { clock: () => now });
  assert.equal(loaded.status().folder, sync); assert.equal(loaded.status().lastCopiedAt, result.lastCopiedAt);
  loaded.setAutomatic(false); now += 86400001; await loaded.tick(); assert.equal(fs.readdirSync(sync).length, 1);
});
test('missing Drive mount keeps a local pending copy, then retries without duplicating the snapshot', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'waqt-drive-offline-'));
  const data = path.join(root, 'data'), sync = path.join(root, 'Drive');
  fs.mkdirSync(sync); const store = new Store(data);
  store.change(s => saveTask(s, { title: 'لن تضيع' }));
  const backup = new DriveBackup(data, () => store.state);
  await backup.configure(sync);
  fs.renameSync(sync, sync + '.offline');
  await assert.rejects(backup.run(), /unavailable/);
  assert.equal(backup.status().lastCopiedAt, null);
  assert.ok(backup.status().pending);
  const local = backup.status().lastLocalPath;
  assert.ok(fs.existsSync(path.join(local, 'data.json')));
  fs.renameSync(sync + '.offline', sync);
  await backup.run();
  assert.equal(backup.status().lastLocalPath, local);
  assert.ok(!backup.status().pending);
  assert.ok(backup.status().lastCopiedAt);
  assert.equal(fs.readdirSync(path.join(data, 'backups')).length, 1);
});
