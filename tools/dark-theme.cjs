// Generates ui/dark.css from the light stylesheets: every color-bearing declaration gets a dark
// counterpart under prefers-color-scheme: dark, in the same order and media nesting, so the
// cascade behaves as in the light theme. Run `node tools/dark-theme.cjs` after changing the CSS;
// tests/dark-theme.test.js fails while dark.css is out of date.
const fs = require('node:fs');
const path = require('node:path');
const ui = path.join(__dirname, '../ui');
const SOURCES = ['styles.css', 'alert.css'];
const BACKGROUND = /^(background|background-color|--bg|--purple-light)$/;
const TEXT = /^(color|--ink|--muted)$/;
// Outlines are focus rings and stay bright.
const BORDER = /^(border|border-color|border-(top|right|bottom|left)(-color)?|--border)$/;
const SHADOW = /^box-shadow$/;
const COLOR = /#[0-9a-fA-F]{3,8}\b|\b(?:white|black)\b|rgba?\([^)]*\)/g;

function parseColor(token) {
  if (token === 'white') return [255, 255, 255, 1];
  if (token === 'black') return [0, 0, 0, 1];
  if (token.startsWith('#')) {
    let hex = token.slice(1);
    if (hex.length <= 4) hex = [...hex].map(c => c + c).join('');
    const n = i => parseInt(hex.slice(i, i + 2), 16);
    return [n(0), n(2), n(4), hex.length === 8 ? n(6) / 255 : 1];
  }
  const [r, g, b, a = 1] = token.slice(token.indexOf('(') + 1, -1).split(/[,\s/]+/).filter(Boolean).map(Number);
  return [r, g, b, a];
}
function toHsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}
function fromHsl(h, s, l) {
  const k = n => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = n => Math.round(255 * (l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1))));
  return [f(0), f(8), f(4)];
}
function format([r, g, b], alpha) {
  return alpha < 1 ? `rgba(${r},${g},${b},${+alpha.toFixed(3)})` : '#' + [r, g, b].map(v => v.toString(16).padStart(2, '0')).join('');
}
// Light surfaces become dark ones of the same hue; text and borders invert their lightness.
// Saturated mid-tones (accents, buttons) and already dark surfaces are kept.
function darken(token, kind) {
  const [r, g, b, alpha] = parseColor(token);
  let [h, s, l] = toHsl([r, g, b]);
  // Neutral grays take the slight blue of the dark background instead of a flat gray.
  if (s < 0.05 && kind !== 'text') { h = 225; s = 0.18; }
  let next = l;
  if (kind === 'background') { if (l > 0.82) next = 0.1 + (1 - l) * 0.9; else if (l > 0.65 && s < 0.4) next = 0.24; else return token; }
  else if (kind === 'text') { if (l < 0.55) next = Math.min(0.92, 0.98 - l * 0.6); else if (l < 0.75 && s < 0.25) next = 0.68; else return token; }
  else if (kind === 'border') { if (l > 0.85 || (l > 0.7 && s < 0.35)) next = 0.22 + (1 - l) * 0.4; else return token; }
  else if (kind === 'shadow') return l < 0.3 && alpha < 1 ? format([0, 0, 0], Math.min(0.6, alpha * 2.5)) : token;
  return format(fromHsl(h, kind === 'background' ? Math.min(s, 0.3) : s, next), alpha);
}
function kindOf(property) {
  if (BACKGROUND.test(property)) return 'background';
  if (TEXT.test(property)) return 'text';
  if (BORDER.test(property)) return 'border';
  if (SHADOW.test(property)) return 'shadow';
  return null;
}
// A tiny parser for this project's CSS: rules, @media blocks and comments, no nesting beyond that.
function* rules(css, media = []) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    if (head.startsWith('@media')) {
      let depth = 1, j = open + 1;
      while (depth && j < css.length) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
      yield* rules(css.slice(open + 1, j - 1), [...media, head]);
      i = j;
    } else {
      const close = css.indexOf('}', open);
      yield { media, selector: head, body: css.slice(open + 1, close) };
      i = close + 1;
    }
  }
}
function generate(sources) {
  const out = ['/* Generated by tools/dark-theme.cjs from ' + SOURCES.join(' and ') + '. Do not edit by hand. */', ':root{color-scheme:light dark}'];
  for (const css of sources) for (const { media, selector, body } of rules(css)) {
    const declarations = body.split(';').map(d => d.trim()).filter(Boolean).flatMap(d => {
      const colon = d.indexOf(':'); const property = d.slice(0, colon).trim(), value = d.slice(colon + 1).trim();
      const kind = kindOf(property);
      return kind ? [`${property}:${value.replace(COLOR, token => darken(token, kind))}`] : [];
    });
    if (!declarations.length) continue;
    const rule = `${selector}{${declarations.join(';')}}`;
    out.push(media.reduceRight((inner, m) => `${m}{${inner}}`, `@media (prefers-color-scheme:dark){${rule}}`));
  }
  return out.join('\n') + '\n';
}
const read = () => SOURCES.map(name => fs.readFileSync(path.join(ui, name), 'utf8'));
module.exports = { generate, darken, read, target: path.join(ui, 'dark.css') };
if (require.main === module) { fs.writeFileSync(module.exports.target, generate(read())); console.log('Wrote ui/dark.css'); }
